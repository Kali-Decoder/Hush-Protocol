#!/usr/bin/env bash
# pre-build.sh — Deploy InstructionSender + register extension on Coston2.
#
# Prerequisites: .env with PRIVATE_KEY, INITIAL_OWNER, CHAIN_URL
#
# Steps:
#   1. Deploy TeeAttestationVerifier + InstructionSender via Hardhat
#   2. Register extension via TeeExtensionRegistry (uses CipherSign Go tools)
#   3. Write config/extension.env
#
# Usage:
#   ./scripts/pre-build.sh
#   ./scripts/pre-build.sh --force   # re-register (new EXTENSION_ID)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
ARC_CONTRACTS_DIR="$(cd "$PROJECT_DIR/../.." && pwd)"

RED='\033[0;31m'; GREEN='\033[0;32m'; CYAN='\033[0;36m'; NC='\033[0m'
log()  { echo -e "${GREEN}[pre-build]${NC} $*"; }
step() { echo -e "\n${CYAN}=== Step $1: $2 ===${NC}"; }
die()  { echo -e "${RED}[pre-build] ERROR:${NC} $*" >&2; exit 1; }

FORCE=false
[[ "${1:-}" == "--force" ]] && FORCE=true

[[ -f "$PROJECT_DIR/.env" ]] && source "$PROJECT_DIR/.env"

CONFIG_OUTPUT="$PROJECT_DIR/config/extension.env"

if [[ -f "$CONFIG_OUTPUT" && "$FORCE" != "true" ]]; then
  die "config/extension.env exists. Use --force to re-register (new EXTENSION_ID)."
fi

step 1 "Deploy TeeAttestationVerifier + InstructionSender"
cd "$ARC_CONTRACTS_DIR"
PRIVATE_KEY="${PRIVATE_KEY:-}" \
pnpm hardhat run scripts/deploy/deploy-tee.ts --network coston2 2>&1

DEPLOYMENT_FILE="$ARC_CONTRACTS_DIR/deployments/coston2.json"
if [[ ! -f "$DEPLOYMENT_FILE" ]]; then
  die "Deployment file not found at $DEPLOYMENT_FILE"
fi

INSTRUCTION_SENDER=$(jq -r '.contracts.InstructionSender // empty' "$DEPLOYMENT_FILE")
TEE_VERIFIER=$(jq -r '.contracts.TeeAttestationVerifier // empty' "$DEPLOYMENT_FILE")

if [[ -z "$INSTRUCTION_SENDER" || -z "$TEE_VERIFIER" ]]; then
  die "Failed to extract InstructionSender or TeeAttestationVerifier from $DEPLOYMENT_FILE"
fi

log "InstructionSender:     $INSTRUCTION_SENDER"
log "TeeAttestationVerifier: $TEE_VERIFIER"

step 2 "Register extension on-chain"
CIPHERSIGN_DIR="${CIPHERSIGN_DIR:-$PROJECT_DIR/.cipher-sign}"
if [[ -d "$CIPHERSIGN_DIR" ]]; then
  log "Using CipherSign tools at $CIPHERSIGN_DIR"
  EXTENSION_ID=$(cd "$CIPHERSIGN_DIR" && ./cipher-sign extension register \
    --chain-url "$CHAIN_URL" \
    --private-key "$PRIVATE_KEY" \
    --sender "$INSTRUCTION_SENDER" \
    2>&1 | grep -oE '0x[a-fA-F0-9]{64}')
else
  log "CipherSign tools not found at $CIPHERSIGN_DIR"
  log "Run register manually via cast:"
  log "  cast send \$TEE_EXTENSION_REGISTRY 'registerExtension(address,uint256,uint256,bytes)' ..."
  EXTENSION_ID="0x$(openssl rand -hex 32)"
fi

if [[ -z "$EXTENSION_ID" ]]; then
  die "Failed to obtain EXTENSION_ID"
fi

log "Extension ID: $EXTENSION_ID"

step 3 "Write config/extension.env"
cat > "$CONFIG_OUTPUT" <<EOF
# Auto-generated by pre-build.sh — $(date -u +%Y-%m-%dT%H:%M:%SZ)
EXTENSION_ID=$EXTENSION_ID
INSTRUCTION_SENDER=$INSTRUCTION_SENDER
EOF

log "Wrote $CONFIG_OUTPUT"
log "Pre-build complete. Next: ./scripts/start-services.sh"
